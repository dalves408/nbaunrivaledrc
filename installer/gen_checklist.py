"""Generate installer/checklist.h from private/input-manifest.json."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "private" / "input-manifest.json"
OUT = Path(__file__).resolve().parent / "checklist.h"

# Known-good LIVE content filename under 584109D4/000D0000/.
PACKAGE_CONTENT_NAME = "FB7DFF22202FF66CE4C264666214182560F1143058"
# Additional verified payload from NBAUnrivaled.zip. The bytes after the
# first 4 KiB match the original package, including all STFS file data.
ADDITIONAL_PACKAGE_HASHES = (
    "2b705d271b1889672b5f5d175be86025799b9a74acde80b7aabb516a60c30b98",
)

CRITICAL = [
    "default.xex",
    "data.zip",
    "data.idx",
    "ArcadeInfo.xml",
    "game_icon.png",
    "achievement01.png",
    "AUDIO/CROWD_LOOP1_V1.OGG",
]


def main() -> None:
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    by = {f["path"].replace("\\", "/"): f for f in data["files"]}
    xex = by["default.xex"]
    h = bytes.fromhex(xex["sha256"])
    package_hashes = dict.fromkeys((data["package_sha256"], *ADDITIONAL_PACKAGE_HASHES))
    lines = [
        "/* Generated by gen_checklist.py from private/input-manifest.json. */",
        "#pragma once",
        "static const unsigned char XEX_SHA256[32] = {",
        "    " + ",".join(str(b) for b in h) + "};",
        "/* Supported inner LIVE packages (title 584109D4). ZIP wrappers are not hashed. */",
        f'#define NBA_PACKAGE_CONTENT_NAME L"{PACKAGE_CONTENT_NAME}"',
        "static const unsigned char NBA_PACKAGE_SHA256[][32] = {",
    ]
    for digest in package_hashes:
        lines.append("    {" + ",".join(str(b) for b in bytes.fromhex(digest)) + "},")
    lines += [
        "};",
        "static const struct { const char *path; unsigned long long size; } NBA_CHECKLIST[] = {",
    ]
    for path in CRITICAL:
        f = by[path]
        lines.append(f'    {{ "{path}", {f["size"]}ULL }},')
    lines.append("};")
    lines.append(f"#define NBA_CHECKLIST_COUNT {len(CRITICAL)}")
    lines.append(f"#define NBA_EXPECTED_FILE_COUNT {len(data['files'])}")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(CRITICAL)} checklist entries, {len(data['files'])} expected files)")
    for digest in package_hashes:
        print(f"package content {PACKAGE_CONTENT_NAME} sha256={digest}")


if __name__ == "__main__":
    main()
